import { Gauge, Info, RefreshCw, Sparkles } from 'lucide-react';
import { useEffect, useState } from 'react';
import { useAssistant } from '../assistant/useAssistant.js';
import { useCan } from '../auth/useAuth.js';
import { Button, Card, EmptyState, PageHeader } from '../ui/core.jsx';
import { Input } from '../ui/form.jsx';
import { KpiCard } from './KpiCard.jsx';
import { useKpis, useRefreshInsights } from './useKpis.js';

export const EXAMPLE_PROMPTS = [
  'Build a heatmap of compressor energy by hour',
  'OEE by machine this week as a bar chart with a target of 85%',
  'kWh per part on the IMM machines over the last 7 days',
  'Top downtime reasons this month',
  'Maintenance cost by asset this month',
  'PM compliance this month as a gauge',
];

const ask = (text) => useAssistant.getState().open({ text, send: true });

const PromptBar = () => {
  const [text, setText] = useState('');
  const submit = (e) => {
    e.preventDefault();
    if (!text.trim()) return;
    ask(text.trim());
    setText('');
  };
  return (
    <form onSubmit={submit} className="mb-5 flex gap-2">
      <Input
        value={text}
        onChange={(e) => setText(e.target.value)}
        placeholder="Ask SARA to build a KPI…"
        aria-label="Ask SARA to build a KPI"
        className="h-10"
      />
      <Button type="submit" variant="ai" icon={Sparkles} className="h-10" disabled={!text.trim()}>
        Build
      </Button>
    </form>
  );
};

const Chips = () => (
  <ul className="flex flex-wrap justify-center gap-2">
    {EXAMPLE_PROMPTS.map((p) => (
      <li key={p}>
        <button
          type="button"
          onClick={() => ask(p)}
          className="rounded-full border border-border bg-surface px-3 py-1.5 text-xs text-fg shadow-card hover:border-ai/40 hover:bg-ai-soft"
        >
          {p}
        </button>
      </li>
    ))}
  </ul>
);

const Empty = ({ canCreate }) => (
  <Card>
    <EmptyState icon={Gauge} title="No KPIs yet">
      {canCreate ? 'Pick an example or describe your own.' : 'An owner or admin can ask SARA to build KPIs.'}
    </EmptyState>
    <div className="mx-auto mb-8 max-w-2xl space-y-5 px-4">
      <div className="ai-edge flex gap-3 rounded-xl px-4 py-3 text-sm text-muted">
        <Info className="mt-0.5 size-4 shrink-0 text-ai" aria-hidden />
        <p>
          KPIs are generated by the SARA assistant. Describe what to track; SARA picks the data, chart and
          time range, shows a live preview, and adds the card here after you confirm.
        </p>
      </div>
      {canCreate && <Chips />}
    </div>
  </Card>
);

const CardSkeleton = () => (
  <div className="rounded-xl border border-border bg-surface p-4" aria-hidden>
    <div className="skeleton mb-2 h-4 w-1/2" />
    <div className="skeleton mb-4 h-3 w-1/4" />
    <div className="skeleton h-52 w-full" />
  </div>
);

/** /kpis — KPI Builder: cards built by the assistant, each with a live viz and an AI insight. */
export const KpisPage = () => {
  const kpis = useKpis();
  const can = useCan('kpis');
  const { mutate: refreshInsights } = useRefreshInsights();
  useEffect(() => {
    refreshInsights();
  }, [refreshInsights]);
  const items = kpis.data?.items ?? [];

  return (
    <div className="mx-auto w-full max-w-7xl px-4 py-6 sm:px-6">
      <PageHeader
        icon={Gauge}
        title="KPI Builder"
        description="Live KPI cards SARA builds from your plant data, each with an AI insight."
      />
      {can.create && <PromptBar />}
      {kpis.isPending ? (
        <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3" aria-busy="true">
          <span className="sr-only">Loading KPIs</span>
          <CardSkeleton />
          <CardSkeleton />
          <CardSkeleton />
        </div>
      ) : kpis.isError ? (
        <Card>
          <EmptyState
            title="Couldn't load KPIs"
            action={
              <Button icon={RefreshCw} onClick={() => kpis.refetch()}>
                Try again
              </Button>
            }
          >
            {kpis.error.message}
          </EmptyState>
        </Card>
      ) : items.length ? (
        <div className="grid gap-4 md:grid-cols-2 xl:grid-cols-3">
          {items.map((k) => (
            <KpiCard key={k._id} kpi={k} canEdit={can.update} />
          ))}
        </div>
      ) : (
        <Empty canCreate={can.create} />
      )}
    </div>
  );
};
