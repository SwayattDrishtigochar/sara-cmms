import { Ellipsis, MessageSquarePlus, RefreshCw, Sparkles, Star, Trash2 } from 'lucide-react';
import { useState } from 'react';
import { toast } from 'sonner';
import { useAssistant } from '../assistant/useAssistant.js';
import { useCan } from '../auth/useAuth.js';
import { formatRelative } from '../lib/format.js';
import { useDeleteRecord } from '../modules/useModules.js';
import { AiProvenance, Button, Card, CardHeader, Spinner } from '../ui/core.jsx';
import { Dialog, Menu, MenuItem, MenuSeparator } from '../ui/overlay.jsx';
import { Viz } from '../viz/Viz.jsx';
import { useExplainKpi, useKpiRun } from './useKpis.js';

const AI_DOWN = new Set([429, 503]);

/** "Generated by gemini-x · 3 h ago" line of a stored AI text ({ text, model, at, mock }). */
export const insightProvenance = (insight) => ({
  model: insight?.mock ? `${insight.model ?? 'SARA'} (mock)` : insight?.model,
  at: insight?.at ? formatRelative(insight.at) : undefined,
});

/** One KPI on the KPI Builder: live viz, AI insight with provenance, refresh / explain / change / delete. */
export const KpiCard = ({ kpi, canEdit, height = 220 }) => {
  const id = kpi._id;
  const run = useKpiRun(id, kpi.updatedAt);
  const explain = useExplainKpi(id);
  const remove = useDeleteRecord('kpis');
  const canDelete = useCan('kpis').delete;
  const [confirming, setConfirming] = useState(false);

  const onExplain = () =>
    explain.mutate(undefined, {
      onError: (err) =>
        toast.error(
          AI_DOWN.has(err.status)
            ? "SARA can't write a new insight right now. The last one stays until it can."
            : err.message,
        ),
    });
  const onChange = () =>
    useAssistant.getState().open({
      text: `Change the KPI "${kpi.title}": `,
      context: { page: 'kpis', recordRef: { module: 'kpis', id, label: kpi.title } },
    });
  const onDelete = () =>
    remove.mutate(
      { id },
      {
        onSuccess: () => {
          setConfirming(false);
          toast.success(`Deleted "${kpi.title}"`);
        },
        onError: (err) => toast.error(err.message),
      },
    );

  const insight = kpi.insight?.text ? kpi.insight : null;
  const prov = insightProvenance(insight);
  const range = run.data?.timeRange?.label ?? kpi.timeRange?.text;
  return (
    <Card className="flex min-w-0 flex-col">
      <CardHeader
        title={
          <span className="flex items-center gap-1.5">
            {kpi.pinned && (
              <Star
                className="size-3.5 shrink-0 fill-current text-warn"
                aria-label="Pinned to Command Center"
              />
            )}
            <span className="truncate">{kpi.title}</span>
          </span>
        }
        subtitle={[range, kpi.unit].filter(Boolean).join(' · ')}
        actions={
          <Menu
            trigger={
              <Button size="iconSm" variant="ghost" icon={Ellipsis} aria-label={`Actions for ${kpi.title}`} />
            }
          >
            <MenuItem icon={RefreshCw} onSelect={() => run.refetch()}>
              Refresh
            </MenuItem>
            {canEdit && (
              <MenuItem icon={Sparkles} onSelect={onExplain}>
                Explain
              </MenuItem>
            )}
            {canEdit && (
              <MenuItem icon={MessageSquarePlus} onSelect={onChange}>
                Change via chat
              </MenuItem>
            )}
            {canDelete && (
              <>
                <MenuSeparator />
                <MenuItem icon={Trash2} danger onSelect={() => setConfirming(true)}>
                  Delete
                </MenuItem>
              </>
            )}
          </Menu>
        }
      />
      <div className="flex flex-1 flex-col gap-3 p-4">
        {run.isPending ? (
          <div className="skeleton w-full" style={{ height }} aria-hidden />
        ) : run.isError ? (
          <div className="grid place-items-center gap-2 py-8 text-center text-sm text-muted">
            <p>Couldn't load this KPI. {run.error.message}</p>
            <Button size="sm" icon={RefreshCw} onClick={() => run.refetch()}>
              Try again
            </Button>
          </div>
        ) : (
          <Viz result={run.data} height={height} className={run.isFetching ? 'opacity-70' : undefined} />
        )}
        {explain.isPending ? (
          <p className="mt-auto flex items-center gap-2 text-xs text-muted">
            <Spinner className="size-3.5" /> SARA is writing an insight…
          </p>
        ) : insight ? (
          <div className="ai-edge mt-auto rounded-lg px-3 py-2">
            <p className="text-sm text-fg">{insight.text}</p>
            <AiProvenance
              model={prov.model}
              at={prov.at}
              onRegenerate={canEdit ? onExplain : undefined}
              className="mt-1"
            />
          </div>
        ) : null}
      </div>
      <Dialog
        open={confirming}
        onOpenChange={setConfirming}
        title="Delete this KPI?"
        size="sm"
        footer={
          <>
            <Button onClick={() => setConfirming(false)}>Cancel</Button>
            <Button variant="danger" icon={Trash2} loading={remove.isPending} onClick={onDelete}>
              Delete
            </Button>
          </>
        }
      >
        <p className="text-sm text-muted">
          "{kpi.title}" disappears from the KPI Builder and the Command Center for everyone. Ask SARA to build
          it again any time.
        </p>
      </Dialog>
    </Card>
  );
};
