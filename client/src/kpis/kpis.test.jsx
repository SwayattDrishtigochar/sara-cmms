import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { MemoryRouter } from 'react-router';
import { Toaster } from 'sonner';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { useAssistant } from '../assistant/useAssistant.js';
import { TooltipProvider } from '../ui/overlay.jsx';
import { KpiPreview, KpiPreviewBlock } from './KpiPreviewBlock.jsx';
import { EXAMPLE_PROMPTS, KpisPage } from './KpisPage.jsx';

const range = { start: '2026-10-09T18:30:00Z', stop: '2026-10-16T18:30:00Z', label: 'last 7 days' };
const kpi = {
  _id: 'k1',
  title: 'Compressor energy today',
  viz: 'number',
  unit: 'kWh',
  timeRange: { text: 'today' },
  sources: [{ key: 'energy', tool: 'energy_consumption', args: {} }],
  pinned: true,
  updatedAt: '2026-10-16T08:00:00Z',
  insight: { text: 'Energy is 12% above last week.', model: 'gemini-flash', at: new Date().toISOString() },
};
const result = {
  viz: 'number',
  title: kpi.title,
  unit: 'kWh',
  value: 842,
  tone: 'neutral',
  timeRange: range,
  warnings: [],
  stats: {},
};

let kpis = [];
let role = 'owner';
let explainStatus = 200;
const reply = (status, data) => ({ ok: status < 400, status, json: async () => data });
const fetchMock = vi.fn(async (url, init = {}) => {
  const path = String(url).replace(/^.*?\/api/, '');
  const method = init.method ?? 'GET';
  const write = role === 'owner';
  if (path === '/auth/me') {
    return reply(200, {
      user: { id: 'u1', name: 'Owner' },
      context: { role, company: {}, can: { kpis: { create: write, update: write, delete: write } } },
    });
  }
  if (path.startsWith('/m/kpis?')) return reply(200, { items: kpis, total: kpis.length });
  if (path === '/kpis/insights/refresh' && method === 'POST') return reply(200, { refreshed: 0 });
  if (path === '/kpis/k1/run') return reply(200, { result });
  if (path === '/kpis/k1/explain' && method === 'POST') {
    return explainStatus === 200
      ? reply(200, { insight: { ...kpi.insight, text: 'Fresh insight' } })
      : reply(explainStatus, { error: { code: 'AI_UNAVAILABLE', message: 'quota' } });
  }
  if (path === '/m/kpis/k1' && method === 'DELETE') return reply(200, { ok: true });
  return reply(404, { error: { message: `Unexpected ${method} ${path}` } });
});
const calls = (method, path) =>
  fetchMock.mock.calls.filter(
    ([url, init = {}]) => String(url).endsWith(`/api${path}`) && (init.method ?? 'GET') === method,
  ).length;

const renderPage = (ui = <KpisPage />) =>
  render(
    <QueryClientProvider client={new QueryClient({ defaultOptions: { queries: { retry: false } } })}>
      <MemoryRouter>
        <TooltipProvider>{ui}</TooltipProvider>
        <Toaster />
      </MemoryRouter>
    </QueryClientProvider>,
  );
const openMenu = async () => {
  const trigger = await screen.findByRole('button', { name: `Actions for ${kpi.title}` });
  fireEvent.keyDown(trigger, { key: 'Enter' });
};

beforeEach(() => {
  kpis = [];
  role = 'owner';
  explainStatus = 200;
  localStorage.setItem('token', 'test-token');
  vi.stubGlobal('fetch', fetchMock);
  vi.stubGlobal(
    'ResizeObserver',
    class {
      observe() {}
      unobserve() {}
      disconnect() {}
    },
  );
  useAssistant.setState({ isOpen: false, text: '', pendingSend: null, context: null });
});
afterEach(() => {
  cleanup();
  fetchMock.mockClear();
  vi.unstubAllGlobals();
  localStorage.clear();
});

describe('KPI Builder page', () => {
  it('empty state explains the assistant and sends an example prompt', async () => {
    renderPage();
    expect(await screen.findByText('No KPIs yet')).toBeTruthy();
    expect(screen.getByText(/KPIs are generated by the SARA assistant/)).toBeTruthy();
    for (const p of EXAMPLE_PROMPTS) expect(screen.getByRole('button', { name: p })).toBeTruthy();
    expect(EXAMPLE_PROMPTS).toHaveLength(6);
    fireEvent.click(screen.getByRole('button', { name: EXAMPLE_PROMPTS[0] }));
    expect(useAssistant.getState()).toMatchObject({ isOpen: true, pendingSend: EXAMPLE_PROMPTS[0] });
    await waitFor(() => expect(calls('POST', '/kpis/insights/refresh')).toBeGreaterThan(0));
  });

  it('the prompt bar opens the assistant and sends the text', async () => {
    renderPage();
    const box = await screen.findByRole('textbox', { name: 'Ask SARA to build a KPI' });
    fireEvent.change(box, { target: { value: 'Shots per hour on IMM 4' } });
    fireEvent.click(screen.getByRole('button', { name: 'Build' }));
    expect(useAssistant.getState().pendingSend).toBe('Shots per hour on IMM 4');
    expect(box.value).toBe('');
  });

  it('viewers see no prompt bar, chips or edit actions', async () => {
    role = 'view';
    kpis = [kpi];
    renderPage();
    expect(await screen.findByText('842')).toBeTruthy();
    expect(screen.queryByRole('textbox')).toBeNull();
    await openMenu();
    expect(await screen.findByRole('menuitem', { name: 'Refresh' })).toBeTruthy();
    expect(screen.queryByRole('menuitem', { name: 'Explain' })).toBeNull();
    expect(screen.queryByRole('menuitem', { name: 'Delete' })).toBeNull();
    expect(screen.queryByRole('button', { name: 'Regenerate' })).toBeNull();
  });
});

describe('KPI card', () => {
  beforeEach(() => {
    kpis = [kpi];
  });

  it('shows the viz, pin and insight with provenance', async () => {
    renderPage();
    expect(await screen.findByText('842')).toBeTruthy();
    expect(screen.getByLabelText('Pinned to Command Center')).toBeTruthy();
    expect(screen.getByText('Energy is 12% above last week.')).toBeTruthy();
    expect(screen.getByText(/Generated by gemini-flash · just now/)).toBeTruthy();
    expect(screen.getByText('Energy is 12% above last week.').closest('.ai-edge')).toBeTruthy();
  });

  it('Refresh re-runs the KPI', async () => {
    renderPage();
    await screen.findByText('842');
    expect(calls('GET', '/kpis/k1/run')).toBe(1);
    await openMenu();
    fireEvent.click(await screen.findByRole('menuitem', { name: 'Refresh' }));
    await waitFor(() => expect(calls('GET', '/kpis/k1/run')).toBe(2));
  });

  it('Explain asks for a new insight; an AI outage keeps the old one with a friendly toast', async () => {
    renderPage();
    await screen.findByText('842');
    fireEvent.click(screen.getByRole('button', { name: 'Regenerate' }));
    await waitFor(() => expect(calls('POST', '/kpis/k1/explain')).toBe(1));
    explainStatus = 429;
    await openMenu();
    fireEvent.click(await screen.findByRole('menuitem', { name: 'Explain' }));
    expect(await screen.findByText(/SARA can't write a new insight right now/)).toBeTruthy();
    expect(screen.getByText('Energy is 12% above last week.')).toBeTruthy();
  });

  it('Change via chat opens the assistant on this KPI without sending', async () => {
    renderPage();
    await openMenu();
    fireEvent.click(await screen.findByRole('menuitem', { name: 'Change via chat' }));
    expect(useAssistant.getState()).toMatchObject({
      isOpen: true,
      text: `Change the KPI "${kpi.title}": `,
      pendingSend: null,
      context: { page: 'kpis', recordRef: { module: 'kpis', id: 'k1', label: kpi.title } },
    });
  });

  it('Delete asks for confirmation first', async () => {
    renderPage();
    await openMenu();
    fireEvent.click(await screen.findByRole('menuitem', { name: 'Delete' }));
    const dialog = await screen.findByRole('dialog', { name: 'Delete this KPI?' });
    expect(calls('DELETE', '/m/kpis/k1')).toBe(0);
    fireEvent.click(within(dialog).getByRole('button', { name: 'Delete' }));
    await waitFor(() => expect(calls('DELETE', '/m/kpis/k1')).toBe(1));
    expect(await screen.findByText(`Deleted "${kpi.title}"`)).toBeTruthy();
  });
});

describe('KPI chat blocks', () => {
  it('preview block shows the live viz and links to the builder once saved', () => {
    renderPage(<KpiPreviewBlock payload={{ id: 'k1', kpi, result }} />);
    expect(screen.getByText('842')).toBeTruthy();
    expect(screen.getByText('Saved')).toBeTruthy();
    expect(screen.getByRole('link', { name: /Open KPI Builder/ }).getAttribute('href')).toBe('/kpis');
  });

  it('confirm preview lists the definition and the changes', () => {
    renderPage(
      <KpiPreview
        payload={{
          kpi: { ...kpi, viz: 'gauge', target: 85, unit: '%' },
          result: { ...result, viz: 'gauge', unit: '%', value: 72, max: 100 },
          changes: [
            { field: 'viz', from: 'number', to: 'gauge' },
            { field: 'timeRange', from: { text: 'last 7 days' }, to: { text: 'last 30 days' } },
          ],
        }}
      />,
    );
    expect(screen.getByText('Gauge')).toBeTruthy();
    expect(screen.getByText('energy ← energy_consumption')).toBeTruthy();
    expect(screen.getByText('85 %')).toBeTruthy();
    const table = screen.getByRole('table', { name: 'Changes' });
    expect(within(table).getByText('number')).toBeTruthy();
    expect(within(table).getByText('gauge')).toBeTruthy();
    expect(within(table).getByText('last 30 days')).toBeTruthy();
  });
});
