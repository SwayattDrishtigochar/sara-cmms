/** Keep "already consumed" stamps when a work order's spare part rows are edited. */
const keepConsumedStamps = ({ existing, patch }) => {
  if (!patch.spareParts) return;
  const stamped = new Map(
    (existing.spareParts ?? []).filter((r) => r.consumedAt).map((r) => [String(r.sparePart), r.consumedAt]),
  );
  for (const row of patch.spareParts) {
    const at = stamped.get(String(row.sparePart));
    if (at) row.consumedAt = at;
  }
};

